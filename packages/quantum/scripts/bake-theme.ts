/**
 * Prebake dist/theme.css for the zero-config install:
 *   import '@paper/quantum/theme.css'
 *
 * Renders the same emitters the runtime `QuantumStyleSheetAdapter` uses
 * (`foundations()` and `block()` from `src/css.ts`); this is a rendering of
 * those emitters, never a re-implementation.
 *
 * Two intentional differences from the runtime adapter:
 * - **Selectors.** The light colour block is emitted twice, on
 *   `[data-theme="quantum-light"]` and on `:root`. The zero-config path is a
 *   bare CSS import with no plugin to set `data-theme`, so the `:root` copy is
 *   what makes it work; the adapter emits colours on the attribute blocks alone
 *   because on the plugin path the theme system owns that attribute. The dark
 *   block (`[data-theme="quantum-dark"]`) is attribute-only in both outputs,
 *   dark being an opt-in, never the default, and carries a `color-scheme: dark`
 *   override here that the adapter instead derives from the selected theme's
 *   `dark` flag.
 * - **Sanitizer response.** The adapter silently skips a `SAFE_IDENT` /
 *   `UNSAFE_CSS` hit because its colours are user-supplied at runtime. Here the
 *   input is first-party `colors.ts`, so any hit is a bug in our own tokens and
 *   fails the build (`strict: true`) rather than shipping a hollow stylesheet.
 *
 * The import graph reaches `@vuetify/v0` (the md1 palette and `hexToRgb`)
 * through `src/design-system.ts`, which Node resolves to `packages/0/dist`:
 * build `@vuetify/v0` first (the root `pnpm build` is topological; locally,
 * `pnpm build:0`).
 */
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { quantumColors, quantumDarkColors } from '../src/colors'
import { block, foundations } from '../src/css'
import { quantumPalette } from '../src/design-system'

// src/colors.ts pins both maps to the same key set with `satisfies`, but
// tsconfig excludes scripts/** from typecheck; re-assert here so a drifted key
// fails the bake instead of shipping a token themed on one side only.
const lightKeys = Object.keys(quantumColors).toSorted()
const darkKeys = Object.keys(quantumDarkColors).toSorted()
if (lightKeys.join(',') !== darkKeys.join(',')) {
  const missing = lightKeys.filter(key => !darkKeys.includes(key))
  const extra = darkKeys.filter(key => !lightKeys.includes(key))
  throw new Error(`[bake-theme] quantumColors/quantumDarkColors key drift: missing in dark [${missing}], extra in dark [${extra}]`)
}

// SPEC.md "Palette": 19 hues x (50..900 + A100..A700 where they exist) plus
// black and white is 256 values, every key `<hue>-<shade>` in lower case.
const PALETTE_KEY = /^(?:[a-z]+(?:-[a-z]+)?-(?:50|[1-9]00|a[1247]00)|black|white)$/
const paletteKeys = Object.keys(quantumPalette)
if (paletteKeys.length !== 256) {
  throw new Error(`[bake-theme] the flattened md1 palette holds ${paletteKeys.length} values, not 256`)
}
for (const key of paletteKeys) {
  if (!PALETTE_KEY.test(key)) throw new Error(`[bake-theme] palette key "${key}" is not <hue>-<shade>`)
}

// `strict` makes block() throw on a sanitizer hit, an empty block and an alias
// source missing from the map: the compile-time `satisfies` on the alias
// tables does not cover this script, so the same guarantees are re-asserted
// at runtime.
const strict = { aliases: true, strict: true }

const here = dirname(fileURLToPath(import.meta.url))
const out = resolve(here, '../dist/theme.css')
const banner = '/* @paper/quantum: prebaked default theme. Generated by scripts/bake-theme.ts. Do not edit. */\n'
// The dark block is attribute-only (no `:root` copy): light stays the
// zero-config default, and `data-theme="quantum-dark"` opts a subtree in.
// `color-scheme` piggybacks on the same attribute because the CSS-only path
// has no plugin to flip it; the runtime adapter instead emits `:root`
// color-scheme from the selected theme's `dark` flag.
const css = banner
  + foundations()
  + block('[data-theme="quantum-light"]', quantumColors, strict)
  + block(':root', quantumColors, strict)
  + block('[data-theme="quantum-dark"]', quantumDarkColors, strict)
  + ':root {\n  color-scheme: light;\n}\n'
  + '[data-theme="quantum-dark"] {\n  color-scheme: dark;\n}\n'

mkdirSync(dirname(out), { recursive: true })
writeFileSync(out, css)
console.log(`[bake-theme] wrote ${out} (${css.length} bytes)`)
